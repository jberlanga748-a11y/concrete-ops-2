      status: "submitted",
      createdBy: "U-1",
      createdByName: "Demo Foreman",
      submittedAt: "2026-04-26T16:30:00Z",
      reviewedAt: "2026-04-26T18:00:00Z",
      crewSummary: "2 finishers and 1 foreman",
      workPerformed: "Placed and finished the front walk.",
      delays: "None",
