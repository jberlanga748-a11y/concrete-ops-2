      generalNotes: "Ready for cure.",
      timeSummary: { totalEntries: 3, totalMinutes: 480, breakMinutes: 30 },
      crewAssignments: [{ id: "A-1", userId: "U-1", userName: "Demo Foreman", roleOnJob: "foreman" }],
